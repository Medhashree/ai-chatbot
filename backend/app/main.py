from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
from app.graph import chatbot
from langchain_core.messages import HumanMessage
from fastapi.responses import StreamingResponse

app = FastAPI()

app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:5173"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


class ChatRequest(BaseModel):
    message: str


@app.get("/")
def root():
    return {
        "message": "AI Chatbot Backend is running!"
    }


@app.post("/chat")
def chat(request: ChatRequest):

    result = chatbot.invoke({
        "messages": [
            HumanMessage(content=request.message)
        ],
        "response": ""
    })

    return {
        "reply": result["response"]
    }


@app.post("/chat/stream")
def chat_stream(request: ChatRequest):

    def generate():

        for chunk, metadata in chatbot.stream(
            {
                "messages": [
                    HumanMessage(content=request.message)
                ],
                "response": ""
            },
            stream_mode="messages" #I want the messages generated by the LLM to be streamed as they arrive.
        ):

            if chunk.content:
                yield chunk.content #Send this piece now, and pause the generator until the next piece is available.

    return StreamingResponse(
        generate(),
        media_type="text/plain"
    )